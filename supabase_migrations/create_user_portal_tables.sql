        'don_hang', 'chi_tiet_don_hang', 'danh_gia',
        'trang_thai_doc', 'theo_doi', 'luot_thich_danh_gia'
    ]) LOOP
        EXECUTE format('CREATE POLICY "Allow read %1$s" ON %1$s FOR SELECT TO authenticated USING (true)', tbl);
        EXECUTE format('CREATE POLICY "Allow insert %1$s" ON %1$s FOR INSERT TO authenticated WITH CHECK (true)', tbl);
        EXECUTE format('CREATE POLICY "Allow update %1$s" ON %1$s FOR UPDATE TO authenticated USING (true)', tbl);
        EXECUTE format('CREATE POLICY "Allow delete %1$s" ON %1$s FOR DELETE TO authenticated USING (true)', tbl);
    END LOOP;
END $$;

