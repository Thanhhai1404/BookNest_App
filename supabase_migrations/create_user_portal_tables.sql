-- ===================== 3. DON_HANG (Đơn hàng mua sách) =====================

CREATE TABLE IF NOT EXISTS don_hang (
    ma_don_hang BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madg CHAR(10) NOT NULL REFERENCES doc_gia(madg),
    ngay_dat TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    -- Thông tin giao hàng
    ho_ten_nhan VARCHAR(100),
    sdt_nhan CHAR(15),
    dia_chi_nhan VARCHAR(500),

    -- Thanh toán
    phuong_thuc_thanh_toan VARCHAR(30) DEFAULT 'vi_booknest',
        -- Enum: 'vi_booknest', 'cod', 'banking', 'momo', 'zalopay'
    tong_tien DECIMAL(18,0) DEFAULT 0,
    phi_van_chuyen DECIMAL(18,0) DEFAULT 0,
    giam_gia DECIMAL(18,0) DEFAULT 0,
    thanh_toan DECIMAL(18,0) DEFAULT 0,   -- tong_tien + phi - giam

    -- Trạng thái
    trang_thai VARCHAR(30) DEFAULT 'cho_xac_nhan',
        -- Enum: 'cho_xac_nhan', 'da_xac_nhan', 'dang_giao', 'da_giao', 'da_huy'
    ghi_chu VARCHAR(500),

    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_donhang_madg ON don_hang(madg);
CREATE INDEX IF NOT EXISTS idx_donhang_trang_thai ON don_hang(trang_thai);
CREATE INDEX IF NOT EXISTS idx_donhang_ngay_dat ON don_hang(ngay_dat DESC);

COMMENT ON TABLE don_hang IS 'Đơn hàng mua sách qua User Portal';

-- ===================== 4. CHI_TIET_DON_HANG =====================

CREATE TABLE IF NOT EXISTS chi_tiet_don_hang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_don_hang BIGINT NOT NULL REFERENCES don_hang(ma_don_hang) ON DELETE CASCADE,
    mads CHAR(10) NOT NULL REFERENCES dau_sach(mads),
    so_luong INTEGER NOT NULL DEFAULT 1,
    don_gia DECIMAL(18,0) NOT NULL DEFAULT 0,
    thanh_tien DECIMAL(18,0) NOT NULL DEFAULT 0,  -- so_luong * don_gia

    CONSTRAINT uq_ctdh_don_sach UNIQUE (ma_don_hang, mads)
);

CREATE INDEX IF NOT EXISTS idx_ctdh_don_hang ON chi_tiet_don_hang(ma_don_hang);

COMMENT ON TABLE chi_tiet_don_hang IS 'Chi tiết sách trong mỗi đơn hàng';

-- ===================== 5. DANH_GIA (Reviews & Ratings) =====================

CREATE TABLE IF NOT EXISTS danh_gia (
    ma_danh_gia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madg CHAR(10) NOT NULL REFERENCES doc_gia(madg),
    mads CHAR(10) NOT NULL REFERENCES dau_sach(mads),

    diem_so INTEGER NOT NULL CHECK (diem_so >= 1 AND diem_so <= 5),
        -- 1-5 sao
    noi_dung TEXT,        -- Nội dung review
    tieu_de VARCHAR(200), -- Tiêu đề review (optional)

    so_thich INTEGER DEFAULT 0,       -- Số lượt thích
    trang_thai VARCHAR(20) DEFAULT 'active',
        -- Enum: 'active', 'hidden', 'reported'

    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    -- Mỗi user chỉ review 1 lần 1 sách
    CONSTRAINT uq_danhgia_user_book UNIQUE (madg, mads)
);

CREATE INDEX IF NOT EXISTS idx_danhgia_madg ON danh_gia(madg);
CREATE INDEX IF NOT EXISTS idx_danhgia_mads ON danh_gia(mads);
CREATE INDEX IF NOT EXISTS idx_danhgia_diem ON danh_gia(diem_so);
CREATE INDEX IF NOT EXISTS idx_danhgia_created ON danh_gia(created_at DESC);

COMMENT ON TABLE danh_gia IS 'Đánh giá / Review sách từ member';

-- ===================== 6. TRANG_THAI_DOC (Reading Status) =====================

CREATE TABLE IF NOT EXISTS trang_thai_doc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madg CHAR(10) NOT NULL REFERENCES doc_gia(madg),
    mads CHAR(10) NOT NULL REFERENCES dau_sach(mads),

    trang_thai VARCHAR(30) NOT NULL DEFAULT 'muon_doc',
        -- Enum: 'muon_doc' (Want to Read), 'dang_doc' (Reading), 'da_doc' (Read)
    tien_do INTEGER DEFAULT 0,  -- % tiến độ đọc (0-100)

    bat_dau_doc TIMESTAMP WITH TIME ZONE,
    doc_xong TIMESTAMP WITH TIME ZONE,

    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    CONSTRAINT uq_trangthai_user_book UNIQUE (madg, mads)
);

CREATE INDEX IF NOT EXISTS idx_trangthai_madg ON trang_thai_doc(madg);
CREATE INDEX IF NOT EXISTS idx_trangthai_mads ON trang_thai_doc(mads);

COMMENT ON TABLE trang_thai_doc IS 'Trạng thái đọc sách của member (want/reading/read)';

-- ===================== 7. THEO_DOI (Follows) =====================

CREATE TABLE IF NOT EXISTS theo_doi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nguoi_theo_doi CHAR(10) NOT NULL REFERENCES doc_gia(madg),  -- Follower
    nguoi_duoc_theo_doi CHAR(10) NOT NULL REFERENCES doc_gia(madg),  -- Following

    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    CONSTRAINT uq_follow UNIQUE (nguoi_theo_doi, nguoi_duoc_theo_doi),
    CONSTRAINT ck_no_self_follow CHECK (nguoi_theo_doi <> nguoi_duoc_theo_doi)
);

CREATE INDEX IF NOT EXISTS idx_theodoi_follower ON theo_doi(nguoi_theo_doi);
CREATE INDEX IF NOT EXISTS idx_theodoi_following ON theo_doi(nguoi_duoc_theo_doi);

COMMENT ON TABLE theo_doi IS 'Quan hệ follow giữa các member';

-- ===================== 8. LUOT_THICH_DANH_GIA (Like review) =====================

CREATE TABLE IF NOT EXISTS luot_thich_danh_gia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madg CHAR(10) NOT NULL REFERENCES doc_gia(madg),
    ma_danh_gia BIGINT NOT NULL REFERENCES danh_gia(ma_danh_gia) ON DELETE CASCADE,

    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    CONSTRAINT uq_like_review UNIQUE (madg, ma_danh_gia)
